// Provide localStorage/sessionStorage.
//
// jsdom defines these as accessors on the window, and vitest's jsdom
// environment does not carry them across when it copies that window onto the
// test global, so anything reading localStorage throws "Cannot read properties
// of undefined". jsdom's own Storage is a per-window in-memory map, which is
// what this stands in for. Guarded, so it disappears if vitest starts copying
// them.
class MemoryStorage implements Storage {
  private data = new Map<string, string>();

  get length(): number {
    return this.data.size;
  }

  clear(): void {
    this.data.clear();
  }

  getItem(key: string): string | null {
    return this.data.has(key) ? (this.data.get(key) as string) : null;
  }

  key(index: number): string | null {
    return [...this.data.keys()][index] ?? null;
  }

  removeItem(key: string): void {
    this.data.delete(key);
  }

  setItem(key: string, value: string): void {
    this.data.set(String(key), String(value));
  }
}

for (const name of ['localStorage', 'sessionStorage'] as const) {
  if (typeof window[name] === 'undefined') {
    Object.defineProperty(window, name, {
      writable: true,
      configurable: true,
      value: new MemoryStorage(),
    });
  }
}